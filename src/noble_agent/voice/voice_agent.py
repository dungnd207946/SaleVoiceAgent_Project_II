"""Enterprise Agent — orchestrates STT final transcript → LLM stream → TTS stream.

Pipeline: text → LLM (SSE streaming) → SentenceBuffer → TTS → PCM out.
Streaming overlap: TTS sentence N plays while LLM generates sentence N+1.
"""


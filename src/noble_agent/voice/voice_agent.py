logger = logging.getLogger("agent")

# Strip emotion tags from display text (show clean text to UI, tags only go to TTS)
_TAG_RE = re.compile(r"\[[^\]]{1,30}\]\s*")

# Addressee-gate soft-pause watchdog (review round 1, Finding 5): if the
# side-talk verdict producer (BaseSession, Task 5) dies between
# pause_playback() and resume_playback(), the pacer must not wedge forever
# waiting on _resume_event — fail OPEN after this many seconds (drop the
# owed ack/replay, let the turn keep going rather than never firing agent_done).
# Coupling: the session-side decision deadline is `addressee_max_pause_ms /
# 1000` (base_session.py::_addr_deadline_s / telephony/session.py::_addr_
# deadline_s, default 4s) and MUST stay well below this watchdog — if that
# setting is ever raised to >= 5s, this watchdog would resume the pacer on
# its own before the session has a chance to decide (both `__init__`s warn
# at startup if that invariant is violated).
_PAUSE_WATCHDOG_S = 5.0


def _voice_family(backend: str) -> str:
    """Group TTS backends by which voice they speak: `elevenlabs` uses the
    ELEVENLABS_* voice settings; everything else (vieneu / vieneu_vllm /
    remote) serves the VIENEU_VOICE_ID preset."""
    return "elevenlabs" if backend == "elevenlabs" else "vieneu"


def _load_ack_assets() -> list[bytes]:
    """Load pre-synthesized bridge-phrase PCM blobs from
    `settings.tool_ack_assets_dir` (generated by scripts/gen_ack_assets.py).
    Returns empty list if the dir doesn't exist — ack path falls back to
    live TTS of `settings.tool_ack_text`.

    Reads `manifest.json` written by the generator and compares against
    the current runtime settings. Sample-rate mismatch is fatal (audio
    would be pitch-shifted like the 8 kHz bug); speed / voice / model
    mismatch only warn — the cached audio is still usable but may sound
    off vs. the live TTS responses.
    """
    import json as _json

    dir_str = getattr(settings, "tool_ack_assets_dir", "") or ""
    if not dir_str:
        return []
    path = Path(dir_str)
    if not path.is_absolute():
        # resolve relative to repo root (three levels up from this file).
        path = Path(__file__).resolve().parent.parent.parent.parent / dir_str
    if not path.is_dir():
        logger.info("[TOOL-ACK] no asset dir at %s — using live TTS fallback", path)
        return []

    # Manifest check — refuse mismatched sample rate, warn on everything
    # else that influences how the audio sounds alongside live TTS.
    manifest_path = path / "manifest.json"
    if manifest_path.is_file():
        try:
            manifest = _json.loads(manifest_path.read_text(encoding="utf-8"))
        except Exception as exc:  # noqa: BLE001
            logger.warning("[TOOL-ACK] bad manifest.json (%s) — ignoring", exc)
            manifest = {}
        if manifest:
            sr = manifest.get("sample_rate")
            if sr and sr != settings.tts_sample_rate:
                logger.warning(
                    "[TOOL-ACK] manifest sample_rate=%s but current=%s — "
                    "refusing to load (audio would play at wrong pitch). "
                    "Regenerate: uv run python scripts/gen_ack_assets.py",
                    sr,
                    settings.tts_sample_rate,
                )
                return []
            drift: list[str] = []
            # Voice comparison is backend-aware: elevenlabs has its own voice
            # id/model/speed settings; every vieneu-family backend (vieneu /
            # vieneu_vllm / remote) speaks the VIENEU_VOICE_ID preset.
            live_family = _voice_family(settings.tts_backend)
            if live_family == "elevenlabs":
                pairs = [
                    ("speed", manifest.get("speed"), settings.elevenlabs_tts_speed),
                    ("voice_id", manifest.get("voice_id"), settings.elevenlabs_tts_voice_id),
                    ("model", manifest.get("model"), settings.elevenlabs_tts_model),
                ]
            else:
                pairs = [("voice_id", manifest.get("voice_id"), settings.vieneu_voice_id)]
            cached_backend = manifest.get("backend")
            if cached_backend and _voice_family(str(cached_backend)) != live_family:
                pairs.append(("backend", cached_backend, settings.tts_backend))
            for key, cached, live in pairs:
                if cached is not None and cached != live:
                    drift.append(f"{key} cached={cached!r} live={live!r}")
            if drift:
                logger.warning(
                    "[TOOL-ACK] manifest drift: %s — acks will still play but "
                    "may not match live TTS. Regenerate when convenient: "
                    "uv run python scripts/gen_ack_assets.py",
                    "; ".join(drift),
                )
    else:
        logger.info(
            "[TOOL-ACK] no manifest.json at %s — loading assets without drift check (old generator?)",
            path,
        )

    assets: list[bytes] = []
    for pcm in sorted(path.glob("*.pcm")):
        if pcm.name == "resume_ack.pcm":
            # Addressee-gate resume ack lives in the same dir but is a
            # separate, dedicated asset — must NOT join the random tool-ack
            # pool (see _load_resume_ack_asset).
            continue
        try:
            assets.append(pcm.read_bytes())
        except Exception as exc:  # noqa: BLE001
            logger.warning("[TOOL-ACK] failed to read %s: %s", pcm, exc)
    if assets:
        logger.info("[TOOL-ACK] loaded %d pre-synth assets from %s", len(assets), path)
    return assets


def _load_resume_ack_asset() -> bytes:
    """PCM pre-synth cho câu resume-ack (gen_ack_assets.py --resume-ack).
    Nằm CẠNH assets dir tool-ack nhưng là file riêng `resume_ack.pcm` —
    KHÔNG nằm trong pool random tool-ack. Thiếu file → b"" (live TTS fallback)."""
    dir_str = getattr(settings, "tool_ack_assets_dir", "") or ""
    if not dir_str:
        return b""
    path = Path(dir_str)
    if not path.is_absolute():
        path = Path(__file__).resolve().parent.parent.parent.parent / dir_str
    f = path / "resume_ack.pcm"
    try:
        return f.read_bytes() if f.is_file() else b""
    except Exception as exc:  # noqa: BLE001
        logger.warning("[RESUME-ACK] failed to read %s: %s", f, exc)
        return b""


class VoiceAgent:
    """Use `await VoiceAgent.create(...)` to construct (async LLM init)."""

    def __init__(
        self,
        send_audio: Callable[[bytes], Awaitable[None]],
        send_json: Callable[[dict], Awaitable[None]],
        session_id: str = "",
        metrics: MetricsCollector | None = None,
        usage_meter=None,
    ):
        self._send_audio = send_audio
        self._send_json = send_json
        self._session_id = session_id
        self._llm = None  # Created in async start()
        self._tts = self._create_tts()
        self._interrupted = False
        if metrics is None:
            from noble_agent.metrics import MetricsCollector

            metrics = MetricsCollector()
        self._metrics = metrics
        self._billing = usage_meter
        # Audio guard 4: repetition detector (CONCERNS.md 7.5 / Phase 4.2).
        # Log-only — we do not suppress responses today, we just flag the
        # loop for metrics + manual review.
        self._repetition_detector = None
        if settings.audio_guard_repetition_detector_enabled:
            from noble_agent.voice.audio_guard import RepetitionDetector

            self._repetition_detector = RepetitionDetector()
        # Pre-synthesized tool-ack PCM assets (loaded once, picked at random
        # per turn). Empty list → fall back to live TTS of tool_ack_text.
        self._ack_assets: list[bytes] = _load_ack_assets()
        # Session-level cooldown so the canned ack doesn't fire on every
        # consecutive slow-tool turn (see tool_ack_cooldown_s / _probability).
        self._last_ack_monotonic: float = 0.0
        # STT latency of the pending user turn, stashed by BaseSession._on_final
        # and consumed once by handle_utterance to tag the transcript event.
        self._last_stt_ms: float | None = None
        # Addressee-gate soft-pause: pacer nín khi _playback_paused, KHÔNG cancel
        # turn. _resume_event set = được chạy. Xem _wait_if_paused.
        self._playback_paused = False
        self._resume_event = asyncio.Event()
        self._resume_event.set()
        self._resume_with_ack = False
        # Display-text các clause đã phát ra loa trong turn hiện tại — context
        # cho addressee classifier (spoken_text_this_turn). Reset đầu handle_utterance.
        self._spoken_texts: list[str] = []
        self._resume_ack_pcm: bytes = _load_resume_ack_asset()

    async def start(self) -> None:
        """Initialize async LLM (loads session from Redis).

        Uses ``NobleAgent`` from ``noble_agent.agent.facade`` —
        active-agent stickiness with per-session context.
        """
        from noble_agent.agent.facade import NobleAgent

        self._llm = await NobleAgent.create(self._session_id, channel="voice")
        await self._llm.ensure_session_started()

    @staticmethod
    def _create_tts():
        """Construct the TTS backend with init-time fallback.

        Tries `resolve_order(settings.tts_backend, TTS_FALLBACK_CHAIN)` — the
        configured primary first, then the rest of the chain. The first builder
        that constructs without raising wins (construction eagerly loads the
        model for vieneu, so a load failure raises here and is caught). An
        unknown backend (not in the chain) maps to vieneu to preserve the
        legacy "anything not elevenlabs → vieneu" contract. If every builder
        raises, the last exception is re-raised — TTS is required, no silent
        None.
        """
        from noble_agent.voice.fallback import TTS_FALLBACK_CHAIN, resolve_order

        def _build_vieneu():
            from noble_agent.voice.tts.vieneu import AsyncVieNeuTTS

            return AsyncVieNeuTTS()

        def _build_vieneu_vllm():
            from noble_agent.voice.tts.vieneu_vllm import AsyncVieNeuVLLMTTS

            return AsyncVieNeuVLLMTTS()

        def _build_eleven():
            from noble_agent.voice.tts.elevenlabs import AsyncElevenLabsTTS

            return AsyncElevenLabsTTS()

        def _build_remote():
            from noble_agent.voice.tts.remote import RemoteTTS

            return RemoteTTS()

        def _build_hotline_ws():
            from noble_agent.voice.tts.hotline_ws import HotlineWsTTS

            return HotlineWsTTS()

        builders = {
            "vieneu": _build_vieneu,
            "vieneu_vllm": _build_vieneu_vllm,
            "elevenlabs": _build_eleven,
            "remote": _build_remote,
            "hotline_ws": _build_hotline_ws,
        }
        order = resolve_order(settings.tts_backend, TTS_FALLBACK_CHAIN)

        last_exc: Exception | None = None
        for name in order:
            try:
                tts = builders.get(name, _build_vieneu)()
            except Exception as exc:  # noqa: BLE001 - try the next backend in the chain
                last_exc = exc
                logger.warning("TTS backend '%s' failed to construct: %s — trying next", name, exc)
                continue
            if name != settings.tts_backend:
                logger.warning("TTS fell back to '%s' (primary '%s' unavailable)", name, settings.tts_backend)
            else:
                logger.info("TTS backend: %s", name)
            return tts
        raise last_exc  # type: ignore[misc]

    async def reset_conversation(self) -> None:
        await self._llm.reset()

    def interrupt(self):
        self._interrupted = True
        if getattr(self, "_resume_event", None) is not None:
            self._release_pause()

    async def pause_tts(self) -> None:
        """Stop agent audio production ASAP.

        Sets the interrupted flag so the streaming `speak_text` /
        `handle_utterance` loops exit on their next iteration. Subclasses /
        TTS backends may override to also close the underlying WebSocket or
        HTTP stream — today the flag is sufficient because the pull loop
        checks it every chunk.

        Safe to call multiple times.
        """
        self._interrupted = True
        if getattr(self, "_resume_event", None) is not None:
            self._release_pause()
        pause = getattr(self._tts, "pause", None)
        if pause is not None:
            try:
                await pause()
            except Exception as exc:  # noqa: BLE001 — pause là best-effort
                logger.warning("pause_tts hook failed: %s", exc)

    def pause_playback(self) -> None:
        """Soft-pause (addressee gate): pacer ngừng gửi frame; turn vẫn sống.
        KHÔNG set _interrupted — llm_producer + synth-ahead chạy tiếp.

        No-op if the turn is already committed to interrupt (Finding 4,
        review round 1): pausing after interrupt() would clear
        `_resume_event` with no consumer left to ever set it again
        (interrupt()'s own `_release_pause()` already ran) — a LATER
        speak_text()/handle_utterance() turn that resets `_interrupted` at
        entry and waits on this same event would then wedge forever.
        """
        if self._interrupted:
            return
        self._playback_paused = True
        self._resume_event.clear()

    def resume_playback(self) -> None:
        """Side-talk verdict: phát ack xin phép rồi phát lại clause đang dở.
        Ack + replay do pacer thực hiện (single writer tới _send_audio)."""
        self._resume_with_ack = True
        self._playback_paused = False
        self._resume_event.set()

    def _release_pause(self) -> None:
        """Commit interrupt trong lúc đang soft-pause: mở khoá để pacer thấy
        _interrupted và thoát — pacer không bao giờ kẹt trên _resume_event."""
        self._playback_paused = False
        self._resume_event.set()

    @property
    def spoken_text_this_turn(self) -> str:
        """Display-text các clause đã phát ra loa trong turn hiện tại — context
        cho addressee classifier. Interrupt giữa turn ⇒ chỉ chứa phần khách ĐÃ nghe."""
        return " ".join(getattr(self, "_spoken_texts", []) or [])

    async def refresh_system_prompt(self) -> None:
        await self._llm.refresh_system_prompt()

    async def _trim_if_interrupted(self, llm_persisted: bool) -> None:
        """Khách ngắt lời sau khi LLM đã trả lời xong (history đã persist toàn bộ câu)
        → nhờ facade cắt về `spoken_text_this_turn`. Best-effort: không bao giờ raise,
        chịu được `_llm` không có hook (test dựng agent bằng MagicMock)."""
        if not (getattr(self, "_interrupted", False) and llm_persisted):
            return
        hook = getattr(self._llm, "note_interrupted", None)
        if not asyncio.iscoroutinefunction(hook):
            return
        try:
            await hook(spoken_text=self.spoken_text_this_turn)
        except Exception:  # noqa: BLE001
            logger.warning("note_interrupted hook failed", exc_info=True)

    def set_voice(self, voice_id: str) -> None:
        self._tts.set_voice(voice_id)

    async def speak_text(self, text: str) -> None:
        self._interrupted = False
        async for chunk in self._tts.stream(normalize_for_voice(text)):
            if self._interrupted:
                break
            try:
                await asyncio.wait_for(self._resume_event.wait(), timeout=_PAUSE_WATCHDOG_S)
            except TimeoutError:
                # Same fail-open watchdog as _wait_if_paused (Finding 5) — a
                # dead verdict producer must not wedge the greeting forever.
                logger.warning(
                    "[ADDRESSEE-GATE] speak_text resume watchdog fired after %.1fs — resuming",
                    _PAUSE_WATCHDOG_S,
                )
                self._playback_paused = False
                self._resume_with_ack = False
                self._resume_event.set()
            if self._interrupted:
                break
            await self._send_audio(chunk)

    async def build_greeting(self, session_id: str) -> str:
        # Tenant-configured opening line (agent_config.greeting) read through
        # the unified facade; empty → a brand-aware default. The line lives
        # here (transport), NOT in SOUL.md — the prompt no longer carries it.
        identity: dict = {}
        try:
            getter = getattr(self._llm, "get_identity", None)
            if getter is not None:
                identity = getter() or {}
        except Exception:
            logger.exception("greeting: get_identity failed")
            identity = {}

        tag_prefix = "[warmly] " if settings.emotion_tags_enabled else ""

        greeting = (identity.get("greeting") or "").strip()
        if greeting:
            return f"{tag_prefix}{greeting}"

        agent_name = identity.get("agent_name") or settings.agent_name
        brand = (identity.get("brand") or "").strip()
        brand_part = f" bên {brand}" if brand else ""
        return (
            f"{tag_prefix}Em chào anh chị, em là {agent_name}{brand_part}. "
            "Anh chị đang quan tâm dự án nào để em tư vấn ạ?"
        )

    async def greet(self, session_id: str) -> None:
        text = await self.build_greeting(session_id)
        logger.info("[AGENT] Auto-greeting: %s", text)
        display_text = _TAG_RE.sub("", text).strip()
        await self._send_json({"type": "agent_speaking", "text": display_text, "turn_id": "greeting"})
        await self.speak_text(text)
        await self._send_json({"type": "agent_done", "turn_id": "greeting"})

    async def _iter_clause_audio(self, sc: SentenceChunk):
        """Yield PCM frames for one clause.

        Pre-synth bridge-phrase shortcut: when the producer stuffed `pcm_data`
        into the chunk (tool-ack), skip live TTS and stream the bytes straight
        through in ~40 ms frames. Otherwise drive the live TTS `stream()`.

        Used by the synth-ahead task; lifted out of the old `tts_consumer`
        closure so it can run ahead of the pacer (and be unit-tested directly).
        Frame math is identical to the previous inline `_iter_audio`.
        """
        if sc.pcm_data:
            # 40 ms @ tts_sample_rate (samples × 2 bytes per int16)
            frame_bytes = int(settings.tts_sample_rate * 0.04) * 2
            data = sc.pcm_data
            for i in range(0, len(data), frame_bytes):
                yield data[i : i + frame_bytes]
            return
        tts_text = normalize_for_voice(sc.text)
        # aclosing → breaking the consumer deterministically closes the TTS
        # stream generator (runs its finally / cancels the remote synth) instead
        # of leaking it to GC. Critical for prompt barge-in cleanup.
        async with contextlib.aclosing(self._tts.stream(tts_text)) as stream:
            async for _chunk in stream:
                yield _chunk

    async def _wait_if_paused(self, clause_frames: list[bytes]) -> bool:
        """Chặn khi đang soft-pause. Trả True nếu bị commit-interrupt trong lúc
        chờ (caller break). Khi resume: phát ack xin phép rồi replay các frame
        đã gửi của clause hiện tại (transport buffer đã bị clear lúc pause).

        Loop-shaped, not straight-line (review round 1, Finding 3): a SECOND
        `pause_playback()` firing mid-ack or mid-replay re-engages the wait
        instead of letting frames race out. `replay_idx` tracks how far the
        replay got so a re-pause never re-sends a frame twice.

        Also fires when only `_resume_with_ack` is pending even though
        `_playback_paused` is already False (Finding 2): that happens when
        pause()+resume() both land while the pacer was blocked on
        `frame_q.get()` (TTS TTFB, hundreds of ms) rather than parked in
        this gate — the ack must not be silently dropped just because the
        gate wasn't actively waiting when resume() fired.

        Bounded by `_PAUSE_WATCHDOG_S` (Finding 5): if the side-talk verdict
        producer dies between pause and resume, fail OPEN — drop the owed
        ack/replay and let the turn continue rather than wedging forever.
        """
        if not self._playback_paused and not self._resume_with_ack:
            return False
        replay_idx = 0
        while True:
            while self._playback_paused:
                try:
                    await asyncio.wait_for(self._resume_event.wait(), timeout=_PAUSE_WATCHDOG_S)
                except TimeoutError:
                    logger.warning(
                        "[ADDRESSEE-GATE] resume watchdog fired after %.1fs — resuming without ack/replay",
                        _PAUSE_WATCHDOG_S,
                    )
                    self._playback_paused = False
                    self._resume_with_ack = False
                    self._resume_event.set()
                    return False
                if self._interrupted:
                    return True

            if self._resume_with_ack:
                self._resume_with_ack = False
                await self._play_resume_ack()
                if self._interrupted:
                    return True
                if self._playback_paused:
                    # Re-paused mid-ack — _play_resume_ack() already re-armed
                    # _resume_with_ack so the eventual next resume replays it.
                    continue

            while replay_idx < len(clause_frames):
                if self._interrupted:
                    return True
                if self._playback_paused:
                    break  # re-paused mid-replay — resume from replay_idx, not 0
                await self._send_audio(clause_frames[replay_idx])
                replay_idx += 1

            if not self._playback_paused:
                return False
            # else: paused again mid-replay — loop back and wait it out.

    async def _play_resume_ack(self) -> None:
        """Ack 'Em xin phép được nói tiếp ạ' — ưu tiên PCM pre-synth, fallback
        live TTS; cả hai đều best-effort (lỗi thì resume thẳng).

        Re-checks `_playback_paused` between frames (Finding 3): a SECOND
        `pause_playback()` firing mid-ack bails out immediately rather than
        finishing the phrase over the top of the new pause. The ack itself
        is NOT resumed mid-phrase (bailing forfeits the frames already
        played) — but `_resume_with_ack` is re-armed so the next resume
        plays the ack again from the start.
        """
        pcm = getattr(self, "_resume_ack_pcm", b"")
        if pcm:
            frame_bytes = int(settings.tts_sample_rate * 0.04) * 2
            for i in range(0, len(pcm), frame_bytes):
                if self._interrupted:
                    return
                if self._playback_paused:
                    self._resume_with_ack = True
                    return
                await self._send_audio(pcm[i : i + frame_bytes])
            return
        text = (getattr(settings, "addressee_resume_ack_text", "") or "").strip()
        if not text:
            return
        try:
            async with contextlib.aclosing(self._tts.stream(normalize_for_voice(text))) as stream:
                async for chunk in stream:
                    if self._interrupted:
                        return
                    if self._playback_paused:
                        self._resume_with_ack = True
                        return
                    await self._send_audio(chunk)
        except Exception as exc:  # noqa: BLE001 — ack là best-effort
            logger.warning("[RESUME-ACK] live TTS failed: %s — resuming without ack", exc)

    async def handle_utterance(self, text: str) -> None:
        if not text.strip():
            return

        self._interrupted = False
        # getattr guards: some existing tests construct VoiceAgent via
        # __new__ and call handle_utterance directly without these attrs
        # (see test_voice_media_forwarding.py) — absent attribute == pause
        # feature untouched, same pattern as _last_stt_ms / _repetition_detector.
        self._playback_paused = False
        self._resume_with_ack = False
        self._spoken_texts = []
        if getattr(self, "_resume_event", None) is not None:
            self._resume_event.set()
        t_start = time.monotonic()
        turn_id = str(uuid.uuid4())
        # Per-turn debug metrics surfaced to the client on `agent_done` so the
        # test UI can render a latency breakdown under each agent message.
        turn_metrics: dict[str, float | int | bool] = {}

        logger.info("New Response Turn Started | turn_id=%s", turn_id)

        # STT latency for this user turn (stashed by BaseSession._on_final right
        # before it triggered us). Consume-once so it can't go stale next turn.
        # getattr keeps __new__-constructed test agents working (see line ~540).
        _stt_ms = getattr(self, "_last_stt_ms", None)
        self._last_stt_ms = None
        transcript_evt: dict = {"type": "transcript", "text": text, "turn_id": turn_id}
        if _stt_ms is not None:
            transcript_evt["stt_ms"] = round(_stt_ms)
        await self._send_json(transcript_evt)

        buf = SentenceBuffer()
        tts_queue: asyncio.Queue[SentenceChunk | None] = asyncio.Queue()
        _last_completed_id = -1
        _response_chunks: list[str] = []  # for repetition detector

        # Bridge-phrase state: fire at most once per turn when a slow tool
        # (RAG / DB / CRM lookup) starts, so the caller hears something
        # instead of ~1-2s of silence while the tool + 2nd LLM call run.
        #
        # Double-ack problem: OpenAI gpt-5.x often streams `tool_calls` chunks
        # BEFORE `content` chunks, so the old point-in-time check on
        # `_llm_emitted_text` fires too early — canned ack plays, then the
        # LLM's own bridge text ("Dạ em tìm thông tin…") plays right after.
        # Caller hears 2 acks back-to-back.
        #
        # Fix: race the canned ack against the LLM. Schedule it with a short
        # delay; if any content token arrives first, cancel the timer. Whoever
        # speaks first wins — always exactly one ack per turn.
        _ack_played = False
        _ack_pending_task: asyncio.Task | None = None
        _llm_emitted_text = False
        _fast_tools = {t.strip() for t in settings.tool_ack_fast_tools.split(",") if t.strip()}

        _llm_ttft_recorded = False
        _llm_t0 = time.monotonic()
        # True khi stream_response đã trả về = orchestrator đã persist câu trả lời đầy đủ.
        # Chỉ khi đó mới cần cắt history về phần khách đã nghe (xem _trim_if_interrupted).
        _llm_persisted = False

        async def llm_producer():
            nonlocal _llm_persisted
            nonlocal _llm_ttft_recorded, _llm_t0

            def on_token(token: str):
                nonlocal _llm_ttft_recorded, _llm_emitted_text, _ack_pending_task
                if not _llm_ttft_recorded:
                    ttft_ms = (time.monotonic() - _llm_t0) * 1000
                    self._metrics.record_latency("llm", "ttft", ttft_ms)
                    turn_metrics["llm_ttft_ms"] = round(ttft_ms)
                    logger.info("LLM TTFT: %.0fms", ttft_ms)
                    _llm_ttft_recorded = True
                if token and token.strip():
                    _llm_emitted_text = True
                    # LLM spoke first — cancel any pending canned ack so the
                    # caller doesn't hear two bridge phrases.
                    if _ack_pending_task is not None and not _ack_pending_task.done():
                        _ack_pending_task.cancel()
                        logger.debug("[TOOL-ACK] cancelled — LLM spoke first")
                _response_chunks.append(token)
                for chunk in buf.add(token):
                    tts_queue.put_nowait(chunk)

            def on_tool_start(name: str, args: dict):
                nonlocal _ack_played, _ack_pending_task
                logger.info("TOOL Calling %s( %s )", name, args)
                asyncio.ensure_future(self._send_json({"type": "tool_start", "tool": name, "args": args}))
                # Bridge phrase: schedule a canned acknowledgement to play
                # ~250 ms from now. If the LLM streams any content token
                # before the timer fires, on_token() cancels this task —
                # so the LLM's own small-talk wins. Otherwise the canned
                # ack plays when the timer elapses. Exactly one ack per turn.
                if _llm_emitted_text:
                    logger.debug(
                        "[TOOL-ACK] suppressed for %s — LLM already spoke",
                        name,
                    )
                    return
                if not (settings.tool_ack_enabled and not _ack_played and name not in _fast_tools):
                    return
                _ack_played = True  # reserve the slot; cancellation still possible

                # Frequency limiters so the caller doesn't hear a bridge phrase
                # before every answer: skip if we acked recently in this session
                # (cooldown), then thin the rest out by probability. The actual
                # timestamp is recorded only when the ack truly plays (inside
                # _deferred_ack), so a cancelled ack doesn't burn the cooldown.
                if (time.monotonic() - self._last_ack_monotonic) < settings.tool_ack_cooldown_s:
                    logger.debug("[TOOL-ACK] suppressed for %s — within cooldown", name)
                    return
                if random.random() > settings.tool_ack_probability:
                    logger.debug("[TOOL-ACK] suppressed for %s — probability thin-out", name)
                    return

                if self._ack_assets:
                    pcm = random.choice(self._ack_assets)
                    ack_chunk = SentenceChunk(
                        id=-1,
                        text="[ack]",  # display-only marker; not spoken
                        is_final=False,
                        pcm_data=pcm,
                    )
                    ack_label = f"pre-synth asset ({len(pcm)} bytes)"
                elif settings.tool_ack_text:
                    ack_chunk = SentenceChunk(
                        id=-1,
                        text=settings.tool_ack_text,
                        is_final=False,
                    )
                    ack_label = "live-TTS fallback"
                else:
                    return

                async def _deferred_ack():
                    try:
                        await asyncio.sleep(0.25)
                    except asyncio.CancelledError:
                        return
                    self._last_ack_monotonic = time.monotonic()
                    tts_queue.put_nowait(ack_chunk)
                    logger.info(
                        "[TOOL-ACK] %s queued for %s (LLM silent 250ms)",
                        ack_label,
                        name,
                    )

                _ack_pending_task = asyncio.create_task(_deferred_ack(), name=f"tool-ack-{name}")

            def on_tool_done(name: str, result: str):
                logger.info("TOOL Done %s", name)
                asyncio.ensure_future(self._send_json({"type": "tool_done", "tool": name}))
                # Voice parity with chat: if the tool returned a media payload (items[]),
                # stream it as a dedicated `media` event so the app renders images/video
                # alongside the spoken text (docs/api/noblex-app-dev-guide.md §3.1/§4.3).
                # Non-media results (e.g. large RAG payloads) are NOT forwarded.
                try:
                    data = json.loads(result)
                except (TypeError, ValueError):
                    data = None
                if isinstance(data, dict) and isinstance(data.get("items"), list) and data["items"]:
                    asyncio.ensure_future(self._send_json({"type": "media", **data}))

            # Unified has no multi-agent switching; on_agent_switch is a no-op.

            llm_t0 = time.monotonic()
            await self._llm.stream_response(
                text,
                on_token=on_token,
                on_tool_start=on_tool_start,
                on_tool_done=on_tool_done,
                interrupt_check=lambda: self._interrupted,
            )
            _llm_persisted = True
            llm_total_ms = (time.monotonic() - llm_t0) * 1000
            self._metrics.record_latency("llm", "total", llm_total_ms)
            turn_metrics["llm_total_ms"] = round(llm_total_ms)
            logger.info("LLM total: %.0fms", llm_total_ms)

            remainder = buf.flush()
            if remainder:
                tts_queue.put_nowait(remainder)
            tts_queue.put_nowait(None)

        # ── Prefetch pipeline (synth-ahead task + pacer) ───────────────────────
        # The synth-ahead task synthesizes clause N+1 WHILE the pacer plays
        # clause N at realtime (synth RTF < 1 → N+1 finishes ahead), removing the
        # per-clause synth gap that caused stutter at sentence seams. Look-ahead
        # depth is 1: `ready_queue` is bounded to maxsize=1, so at most 2 clauses
        # of audio are buffered (one playing, one ready).
        #
        # Each ready item is `(sc, frame_q)` where frame_q is an asyncio.Queue of
        # PCM frames terminated by a `None` sentinel. The end-of-turn sentinel is
        # `_READY_END`.
        ready_queue: asyncio.Queue = asyncio.Queue(maxsize=1)
        _READY_END = object()

        async def _synth_ahead():
            """Pull SentenceChunks in order; synth each into a per-clause frame
            buffer enqueued on `ready_queue`. The `_iter_clause_audio` helper is
            the SAME audio source as before (pcm_data passthrough OR live TTS)."""
            while True:
                if self._interrupted:
                    break
                sc = await tts_queue.get()
                if sc is None:
                    break

                frame_q: asyncio.Queue = asyncio.Queue()
                # `meta` carries this clause's measured ttfb to the pacer so the
                # `agent_speaking` event can surface it in the live UI log. Filled
                # below when the first frame is produced (before it lands on
                # frame_q), so the pacer always reads it after dequeuing frame 1.
                meta: dict = {}
                # Look-ahead depth 1: this `put` blocks until the pacer has taken
                # the previously-readied clause, bounding buffered audio. On
                # interrupt the pacer cancels this task, so a blocked put is fine
                # to cancel (no deadlock).
                await ready_queue.put((sc, frame_q, meta))

                # Measure TRUE synth latency here, not in the pacer: a prefetched
                # clause's frames are already buffered by the time the pacer dequeues
                # them, so a pacer-side ttfb would read ~0. tts.ttfb = synth start →
                # first frame; tts.total = synth start → last frame. (e2e.ttfa, the
                # caller-perceived first audio, stays in the pacer.)
                synth_t0 = time.monotonic()
                synth_first = True
                _tts_bytes = 0
                async with contextlib.aclosing(self._iter_clause_audio(sc)) as clause:
                    async for frame in clause:
                        if self._interrupted and settings.interrupt_mode == "immediate":
                            break
                        if synth_first:
                            ttfb_ms = (time.monotonic() - synth_t0) * 1000
                            self._metrics.record_latency("tts", "ttfb", ttfb_ms)
                            meta["ttfb_ms"] = round(ttfb_ms)
                            synth_first = False
                        _tts_bytes += len(frame)
                        await frame_q.put(frame)
                if not synth_first:
                    _total_ms = (time.monotonic() - synth_t0) * 1000
                    self._metrics.record_latency("tts", "total", _total_ms)
                    if self._billing is not None:
                        # units = số clause synth; ký tự (cơ sở tính tiền của
                        # vendor đếm chữ như ElevenLabs) đi cột text_units.
                        self._billing.add_audio(
                            "tts",
                            audio_sec=_tts_bytes / (settings.tts_sample_rate * 2),
                            wall_ms=_total_ms,
                            units=1,
                            text_units=len(getattr(sc, "text", "") or ""),
                        )
                await frame_q.put(None)  # clause-complete sentinel

            await ready_queue.put(_READY_END)

        async def _pacer():
            nonlocal _last_completed_id
            first_audio = True
            synth_task = asyncio.ensure_future(_synth_ahead())

            async def _drain_and_cancel_synth():
                """On interrupt: cancel the synth-ahead task and drain any pending
                ready_queue item so a blocked `ready_queue.put` unblocks before the
                cancel takes effect (deadlock-free)."""
                synth_task.cancel()
                try:
                    while True:
                        ready_queue.get_nowait()
                except asyncio.QueueEmpty:
                    pass
                with contextlib.suppress(asyncio.CancelledError):
                    await synth_task

            try:
                while True:
                    if self._interrupted:
                        await self._send_json(
                            {
                                "type": "agent_interrupted",
                                "turn_id": turn_id,
                                "last_completed_sentence_id": _last_completed_id,
                            }
                        )
                        await _drain_and_cancel_synth()
                        break

                    item = await ready_queue.get()
                    if item is _READY_END:
                        # Pacer already exiting: a pause_playback() arriving
                        # from here on has no gate left to park it in. Its
                        # owed ack is dropped — acceptable (Finding 2):
                        # handle_utterance's next-turn reset clears
                        # _playback_paused/_resume_with_ack so nothing wedges.
                        break
                    sc, frame_q, meta = item

                    if self._interrupted:
                        await self._send_json(
                            {
                                "type": "agent_interrupted",
                                "turn_id": turn_id,
                                "last_completed_sentence_id": _last_completed_id,
                            }
                        )
                        await _drain_and_cancel_synth()
                        break

                    # Clause-boundary gate (Finding 2): without this, a pause
                    # arriving while the pacer is blocked on `ready_queue.get()`
                    # (i.e. between clauses) is only observed one clause late,
                    # once the inner loop starts pulling frames. Empty frame
                    # list — nothing has played for this clause yet, so a
                    # replay here is correctly a no-op; only the ack plays.
                    if await self._wait_if_paused([]):
                        await self._send_json(
                            {
                                "type": "agent_interrupted",
                                "turn_id": turn_id,
                                "last_completed_sentence_id": _last_completed_id,
                            }
                        )
                        await _drain_and_cancel_synth()
                        break

                    tts_first_chunk = True
                    sent_speaking = False
                    interrupted_mid_tts = False
                    clause_frames: list[bytes] = []

                    while True:
                        if self._interrupted and settings.interrupt_mode == "immediate":
                            interrupted_mid_tts = True
                            break
                        chunk = await frame_q.get()
                        if chunk is None:  # clause-complete sentinel
                            break
                        if await self._wait_if_paused(clause_frames):
                            interrupted_mid_tts = True
                            break

                        if tts_first_chunk:
                            # tts.ttfb/tts.total are recorded in _synth_ahead now;
                            # this flag only gates _last_completed_id (clause emitted ≥1 frame).
                            tts_first_chunk = False

                        if not sent_speaking:
                            display_text = _TAG_RE.sub("", sc.text).strip()
                            await self._send_json(
                                {
                                    "type": "agent_speaking",
                                    "text": display_text,
                                    "turn_id": turn_id,
                                    "sentence_id": sc.id,
                                    "ttfb_ms": meta.get("ttfb_ms"),
                                }
                            )
                            sent_speaking = True
                            self._spoken_texts.append(display_text)

                        if first_audio:
                            e2e_ttfa_ms = (time.monotonic() - t_start) * 1000
                            self._metrics.record_latency("e2e", "ttfa", e2e_ttfa_ms)
                            logger.info("E2E TTFA: %.0fms", e2e_ttfa_ms)
                            first_audio = False

                        clause_frames.append(chunk)
                        await self._send_audio(chunk)

                    if not interrupted_mid_tts and not tts_first_chunk:
                        _last_completed_id = sc.id

                    if self._interrupted and settings.interrupt_mode == "finish_current" and not interrupted_mid_tts:
                        await self._send_json(
                            {
                                "type": "agent_interrupted",
                                "turn_id": turn_id,
                                "last_completed_sentence_id": _last_completed_id,
                            }
                        )
                        await _drain_and_cancel_synth()
                        break

                    if self._interrupted and interrupted_mid_tts:
                        await self._send_json(
                            {
                                "type": "agent_interrupted",
                                "turn_id": turn_id,
                                "last_completed_sentence_id": _last_completed_id,
                            }
                        )
                        await _drain_and_cancel_synth()
                        break
            finally:
                # Backstop: never leave the synth-ahead task running (e.g. on an
                # exception or outer cancel). Idempotent with _drain_and_cancel_synth.
                if not synth_task.done():
                    synth_task.cancel()
                    with contextlib.suppress(asyncio.CancelledError):
                        await synth_task

            turn_metrics["interrupted"] = self._interrupted
            await self._send_json({"type": "agent_done", "turn_id": turn_id, "metrics": turn_metrics})

        # Transport ngắt lời bằng CANCEL task này (base_session / telephony) — mọi việc
        # sau gather chỉ chạy ở đường "pacer tự thoát vì cờ"; đường cancel phải bắt
        # CancelledError để cắt history rồi mới ném tiếp.
        try:
            await asyncio.gather(llm_producer(), _pacer())
        except asyncio.CancelledError:
            await self._trim_if_interrupted(_llm_persisted)
            raise
        await self._trim_if_interrupted(_llm_persisted)

        if self._interrupted and _last_completed_id >= 0:
            self._llm.set_interrupt_context(last_spoken_sentence_id=_last_completed_id)

        # Audio guard 4 (CONCERNS.md 7.5): check/record full response for
        # repetition. Log-only today — suppression is deferred until we have
        # a safe fallback path (Phase 5 integration coverage).
        # `getattr` keeps test code that constructs VoiceAgent via __new__()
        # (bypassing __init__) working — absent attribute == feature off.
        repetition = getattr(self, "_repetition_detector", None)
        if repetition is not None and not self._interrupted:
            full_response = "".join(_response_chunks).strip()
            if full_response:
                if repetition.is_repetition(full_response):
                    self._metrics.record_latency("guard", "repetition_detected", 1.0)
                else:
                    repetition.record(full_response)
